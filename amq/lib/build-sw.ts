// Writes dist/sw.js after `astro build`, so the site opens offline once
// visited.

import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const DIST = join(import.meta.dirname, '../../dist');
// 26 MB of old demos and the v1 snapshot: cached when visited, not up front.
const ON_VISIT = ['/demos/', '/v1/'];

const files = (await walk(DIST))
  .map((path) => `/${path}`)
  .filter((url) => url !== '/sw.js' && !ON_VISIT.some((prefix) => url.startsWith(prefix)))
  .sort();

const urls = files.map(cleanUrl);
const version = await contentHash(files);

await writeFile(join(DIST, 'sw.js'), serviceWorker(version, urls));
console.log(`Wrote dist/sw.js — precaching ${urls.length} files (cache amatiasq-${version})`);

// Pages are linked with a trailing slash, never by their index.html.
function cleanUrl(url: string): string {
  return url.endsWith('/index.html') ? url.slice(0, -'index.html'.length) : url;
}

// The contents, not the list: a page whose text changed keeps its name, and
// a list-derived name would leave every visitor on the old copy.
async function contentHash(urls: string[]): Promise<string> {
  const digest = createHash('sha256');
  for (const url of urls) {
    digest.update(url);
    digest.update(await readFile(join(DIST, url)));
  }
  return digest.digest('hex').slice(0, 12);
}

async function walk(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true, recursive: true });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => relative(DIST, join(entry.parentPath, entry.name)));
}

function serviceWorker(version: string, urls: string[]): string {
  return `// Generated by amq/lib/build-sw.ts — do not edit.
const CACHE = 'amatiasq-${version}';
const PRECACHE = ${JSON.stringify(urls, null, 2)};
const ON_VISIT = ${JSON.stringify(ON_VISIT)};
// The rest of the domain is nginx's: redirects, proxies, loose files.
const OURS = new Set(PRECACHE);

// One missing file must not abort the whole install.
function cacheAll(cache, urls) {
  return Promise.all(
    urls.map((url) => cache.add(new Request(url, { cache: 'reload' })).catch(() => {})),
  );
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      await cacheAll(await caches.open(CACHE), PRECACHE);
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (!OURS.has(url.pathname) && !ON_VISIT.some((prefix) => url.pathname.startsWith(prefix))) return;

  event.respondWith(
    (async () => {
      const cached = await caches.match(request, { ignoreSearch: true });
      if (cached) return cached;

      try {
        const response = await fetch(request);
        if (response.ok) {
          const cache = await caches.open(CACHE);
          cache.put(request, response.clone());
        }
        return response;
      } catch {
        const home = request.mode === 'navigate' && (await caches.match('/'));
        if (home) return home;
        throw new Error('offline and not cached');
      }
    })(),
  );
});
`;
}
